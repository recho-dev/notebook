/**
 * ============================================================================
 * =                       Box-Drawing Writing                                =
 * ============================================================================
 *
 * Unicode box-drawing characters live in a tight range of code points. Treat
 * those codes as numbers, and a little arithmetic becomes a writing generator:
 * round a code to get a glyph, add noise to pick among its neighbors.
 *
 * Pick a pattern with the radio — the grid fills in character by character.
 * Scroll down for a static catalog with the math behind each formula.
 *
 * The whole trick is `char` and `rand`:
 *
 * - `char(x)` rounds `x` and looks up that Unicode code point
 * - `rand(n)` is noise in `[-n/2, n/2)`
 * - `round(rand(1) + 0.5)` is a coin flip: `0` or `1`
 *
 * Shifting the base (`9585.1` vs `9585.5`) biases which glyph wins. Multiplying
 * the coin flip stretches the jump, so you can hop from ╱ to ╳, or from ━ to ┓.
 */

